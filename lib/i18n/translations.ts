export type Lang = 'en' | 'zh' | 'zh-Hant';

/** Normalize a cookie/header value to a supported language. */
export function resolveLang(value: string | null | undefined): Lang {
  if (value === 'en') return 'en';
  if (value === 'zh-Hant') return 'zh-Hant';
  return 'zh';
}

/** Cycle order: 简体 → 繁體 → English → 简体 */
export const langCycle: Lang[] = ['zh', 'zh-Hant', 'en'];
export const langLabels: Record<Lang, string> = {
  zh: '简体中文',
  'zh-Hant': '繁體中文',
  en: 'English',
};

export function nextLang(lang: Lang): Lang {
  return langCycle[(langCycle.indexOf(lang) + 1) % langCycle.length];
}

export function htmlLangAttr(lang: Lang): string {
  return lang === 'zh' ? 'zh-CN' : lang === 'zh-Hant' ? 'zh-Hant' : 'en';
}

